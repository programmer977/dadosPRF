def sha256_arquivo(caminho):
    h = hashlib.sha256()
    with caminho.open('rb') as f:
        for bloco in iter(lambda: f.read(1024 * 1024), b''):
            h.update(bloco)
    return h.hexdigest()


def carregar_auditar(ano):
    caminho = localizar(ano)
    dados = pd.read_csv(
        caminho, sep=';', encoding='latin1', decimal=',',
        dtype={'id':'string', 'br':'string'}, low_memory=False
    )
    obrigatorias = {'id','data_inversa','horario','causa_acidente','br','uf'}
    faltantes = obrigatorias - set(dados.columns)
    if faltantes:
        raise ValueError(f'Colunas ausentes em {ano}: {sorted(faltantes)}')

    # Preserva os dados originais, e padroniza apenas campos textuais.
    for coluna in dados.select_dtypes(include=['object','string']).columns:
        dados[coluna] = (dados[coluna].astype('string')
                         .str.normalize('NFKC').str.strip()
                         .str.replace(r'\s+', ' ', regex=True)
                         .replace('', pd.NA))

    duplicatas = int(dados.duplicated().sum())
    dados = dados.drop_duplicates().copy()
    dados['data_inversa'] = pd.to_datetime(
        dados['data_inversa'], format='%Y-%m-%d', errors='coerce'
    )
    validas = dados['data_inversa'].dt.year.eq(ano).fillna(False)
    rejeitadas = dados.loc[~validas].copy()
    if not rejeitadas.empty:
        rejeitadas.to_csv(SAIDA / f'rejeitados_data_{ano}.csv', index=False)
    dados = dados.loc[validas].copy()

    dados['hora'] = pd.to_datetime(
        dados['horario'], format='%H:%M:%S', errors='coerce'
    ).dt.hour.astype('Int64')
    numericas = ['km','latitude','longitude','pessoas','mortos','feridos_leves',
                 'feridos_graves','ilesos','ignorados','feridos','veiculos']
    for coluna in numericas:
        if coluna in dados.columns and not pd.api.types.is_numeric_dtype(dados[coluna]):
            dados[coluna] = pd.to_numeric(
                dados[coluna].astype('string').str.replace(',', '.', regex=False),
                errors='coerce'
            )

    dados['ano'] = ano
    dados['mes'] = dados['data_inversa'].dt.month.astype('int8')
    br_valida = dados['br'].str.fullmatch(r'\d+').fillna(False)
    dados['rodovia'] = ('BR-' + dados['br'].str.zfill(3)).where(br_valida, 'BR não identificada')
    dados['causa_acidente'] = dados['causa_acidente'].fillna('Não informada')

    dados['id_suspeito'] = ~dados['id'].str.fullmatch(r'\d+').fillna(False)
    dados['id_duplicado'] = dados['id'].duplicated(keep=False)
    partes = ['mortos','feridos_leves','feridos_graves','ilesos','ignorados']
    if {'pessoas',*partes}.issubset(dados.columns):
        dados['pessoas_divergentes'] = dados['pessoas'].ne(
            dados[partes].sum(axis=1, min_count=len(partes))
        ).fillna(True)
    else:
        dados['pessoas_divergentes'] = pd.NA

    resumo = {
        'ano':ano, 'arquivo':caminho.name, 'sha256':sha256_arquivo(caminho),
        'registros_brutos': len(dados) + duplicatas + len(rejeitadas),
        'duplicatas_exatas_removidas':duplicatas,
        'datas_rejeitadas':len(rejeitadas), 'registros_validos':len(dados),
        'data_maxima':dados['data_inversa'].max().date().isoformat(),
        'hora_invalida':int(dados['hora'].isna().sum()),
        'id_suspeito':int(dados['id_suspeito'].sum()),
        'id_duplicado':int(dados['id_duplicado'].sum()),
        'pessoas_divergentes':int(dados['pessoas_divergentes'].sum())
    }
    return dados, resumo

