def limpar_dados(ano, nome_arquivo):

    caminho = PASTA / nome_arquivo

    if not caminho.is_file():
        raise FileNotFoundError(
            f"Arquivo não encontrado: {caminho}"
        )

    print(f"\n{'=' * 50}")
    print(f"PROCESSANDO BASE DE {ano}")
    print(f"{'=' * 50}")

    # IMPORTAÇÃO
    df = pd.read_csv(
        caminho,
        sep=";",
        encoding="latin1",
        decimal=",",
        dtype={
            "id": "string",
            "br": "string"
        },
        low_memory=False
    )

    total_original = len(df)

    # ------------------------------------------------------
    # 2.1. PADRONIZAÇÃO DOS TEXTOS
    # ------------------------------------------------------

    for coluna in df.select_dtypes(
        include=["object", "string"]
    ).columns:

        df[coluna] = (
            df[coluna]
            .astype("string")
            .str.normalize("NFKC")
            .str.strip()
            .str.replace(r"\s+", " ", regex=True)
        )

        df[coluna] = df[coluna].replace("", pd.NA)

    # ------------------------------------------------------
    # 2.2. REMOÇÃO DE DUPLICATAS EXATAS
    # ------------------------------------------------------

    duplicatas = df.duplicated().sum()

    df = df.drop_duplicates().copy()

    # ------------------------------------------------------
    # 2.3. TRATAMENTO DAS DATAS
    # ------------------------------------------------------

    df["data_inversa"] = pd.to_datetime(
        df["data_inversa"],
        format="%Y-%m-%d",
        errors="coerce"
    )

    datas_validas = df["data_inversa"].dt.year.eq(ano)

    datas_invalidas = (~datas_validas).sum()

    df = df.loc[datas_validas].copy()

    # ------------------------------------------------------
    # 2.4. TRATAMENTO DOS HORÁRIOS
    # ------------------------------------------------------

    horarios = pd.to_datetime(
        df["horario"],
        format="%H:%M:%S",
        errors="coerce"
    )

    df["hora"] = horarios.dt.hour.astype("Int64")

    # ------------------------------------------------------
    # 2.5. CONVERSÃO DOS DADOS NUMÉRICOS
    # ------------------------------------------------------

    for coluna in COLUNAS_NUMERICAS:

        if coluna not in df.columns:
            continue

        if not pd.api.types.is_numeric_dtype(df[coluna]):

            valores = (
                df[coluna]
                .astype("string")
                .str.replace(",", ".", regex=False)
            )

            df[coluna] = pd.to_numeric(
                valores,
                errors="coerce"
            )

    # ------------------------------------------------------
    # 2.6. PADRONIZAÇÃO DAS RODOVIAS
    # ------------------------------------------------------

    br = df["br"].astype("string")

    br_valida = br.str.fullmatch(r"\d{1,3}").fillna(False)

    df["rodovia"] = pd.Series(
        pd.NA,
        index=df.index,
        dtype="string"
    )

    df.loc[br_valida, "rodovia"] = (
        "BR-" + br.loc[br_valida].str.zfill(3)
    )

    # ------------------------------------------------------
    # 2.7. CRIAÇÃO DAS COLUNAS TEMPORAIS
    # ------------------------------------------------------

    df["ano"] = df["data_inversa"].dt.year.astype(int)

    df["mes"] = df["data_inversa"].dt.month.astype(int)

    df["dia"] = df["data_inversa"].dt.day.astype(int)

    # ------------------------------------------------------
    # 2.8. VERIFICAÇÃO DOS IDENTIFICADORES
    # ------------------------------------------------------

    df["id_suspeito"] = ~(
        df["id"]
        .str.fullmatch(r"\d+")
        .fillna(False)
    )

    df["id_duplicado"] = df["id"].duplicated(
        keep=False
    )

    # ------------------------------------------------------
    # 2.9. VERIFICAÇÃO DA CONTAGEM DE PESSOAS
    # ------------------------------------------------------

    soma_pessoas = df[COLUNAS_PESSOAS].sum(
        axis=1,
        min_count=len(COLUNAS_PESSOAS)
    )

    df["pessoas_inconsistentes"] = (
        df["pessoas"]
        .ne(soma_pessoas)
        .fillna(True)
    )

    # ------------------------------------------------------
    # 2.10. EXPORTAÇÃO DO CSV LIMPO
    # ------------------------------------------------------

    nome_saida = f"datatran{ano}_limpo.csv"

    caminho_saida = SAIDA / nome_saida

    df.to_csv(
        caminho_saida,
        sep=";",
        index=False,
        encoding="utf-8-sig",
        decimal=",",
        date_format="%Y-%m-%d"
    )

    # ------------------------------------------------------
    # 2.11. RELATÓRIO DE LIMPEZA
    # ------------------------------------------------------

    print(f"\nRegistros originais: {total_original:,}")
    print(f"Duplicatas removidas: {duplicatas:,}")
    print(f"Datas inválidas removidas: {datas_invalidas:,}")
    print(f"Registros finais: {len(df):,}")

    print(
        f"Período: {df['data_inversa'].min().date()} "
        f"até {df['data_inversa'].max().date()}"
    )

    print(f"Horários inválidos: {df['hora'].isna().sum():,}")

    print(f"IDs suspeitos: {df['id_suspeito'].sum():,}")

    print(f"IDs duplicados: {df['id_duplicado'].sum():,}")

    print(
        "Contagens de pessoas inconsistentes:",
        f"{df['pessoas_inconsistentes'].sum():,}"
    )

    print(f"\nArquivo gerado: {caminho_saida}")

    return df, caminho_saida


