faltantes = set(colunas) - set(df.columns)

if faltantes:
    raise ValueError(f"Colunas ausentes: {faltantes}")

# ==========================================================
# 2. PREPARAÇÃO DOS INDICADORES DE GRAVIDADE
# ==========================================================

df["mortos"] = pd.to_numeric(
    df["mortos"], errors="coerce"
)

df["feridos_graves"] = pd.to_numeric(
    df["feridos_graves"], errors="coerce"
)

# Não considerar contagens negativas como válidas
df.loc[df["mortos"] < 0, "mortos"] = float("nan")
df.loc[df["feridos_graves"] < 0, "feridos_graves"] = float("nan")

# Identificar acidentes com pelo menos uma morte
df["acidente_fatal"] = (
    df["mortos"].gt(0)
    .astype("Float64")
    .where(df["mortos"].notna())
)

# Identificar acidentes com pelo menos um ferido grave
df["acidente_com_ferido_grave"] = (
    df["feridos_graves"].gt(0)
    .astype("Float64")
    .where(df["feridos_graves"].notna())
)


# ==========================================================
# 3. FUNÇÃO DE ANÁLISE
# ==========================================================

def analisar_gravidade(dados, agrupamento):

    resultado = dados.groupby(
        agrupamento, dropna=False
    ).agg(
        total_acidentes=("ano", "size"),

        acidentes_com_mortes_informadas=("mortos", "count"),

        acidentes_fatais=("acidente_fatal", "sum"),

        total_mortes=("mortos", "sum"),

        acidentes_com_graves_informados=("feridos_graves", "count"),

        acidentes_com_feridos_graves=(
            "acidente_com_ferido_grave", "sum"
        ),

        total_feridos_graves=("feridos_graves", "sum")

    ).reset_index()

    # Percentual de acidentes com vítimas fatais
    resultado["percentual_fatal"] = (
        resultado["acidentes_fatais"]
        / resultado["acidentes_com_mortes_informadas"]
        .replace(0, float("nan"))
    ) * 100

    # Mortes para cada 100 acidentes com informação válida
    resultado["mortes_por_100_acidentes"] = (
        resultado["total_mortes"]
        / resultado["acidentes_com_mortes_informadas"]
        .replace(0, float("nan"))
    ) * 100

    # Percentual de acidentes com feridos graves
    resultado["percentual_com_feridos_graves"] = (
        resultado["acidentes_com_feridos_graves"]
        / resultado["acidentes_com_graves_informados"]
        .replace(0, float("nan"))
    ) * 100

    return resultado


